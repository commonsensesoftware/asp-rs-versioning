use http::header::{ACCEPT, CONTENT_TYPE};
use smallvec::SmallVec;
use std::borrow::Cow;

const DEFAULT_WEIGHT: f32 = 1.0;

/// Represents an API version reader that reads the value from a media type HTTP header in the request.
///
/// # Examples
///
/// ```
/// use api_versioning::{pattern, readers::MediaTypeReader};
///
/// // matches 'application/json;v=1.0'
/// let reader = MediaTypeReader::default();
///
/// // matches 'application/json;ver=1.0'
/// let reader = MediaTypeReader::new("ver");
///
/// // matches 'application/json;v=1.0' or 'application/json;ver=1.0'
/// let reader = MediaTypeReader::new(["v", "ver"]);
///
/// // matches 'application/vnd.1.0'
/// let reader = MediaTypeReader::template(pattern!(application/vnd.{v}));
/// ```
#[derive(Clone, Debug)]
pub struct MediaTypeReader(Matcher);

#[derive(Clone, Debug)]
enum Matcher {
    Parameters(SmallVec<[Cow<'static, str>; 1]>),
    Template(fn(&str) -> Option<&str>),
}

impl Default for MediaTypeReader {
    fn default() -> Self {
        Self::new("v")
    }
}

impl MediaTypeReader {
    /// Initializes a new [MediaTypeReader].
    ///
    /// # Arguments
    ///
    /// * `names` - one or more media type parameters to read the API version from
    pub fn new(names: impl IntoNames) -> Self {
        Self(Matcher::Parameters(names.into_names()))
    }

    /// Initializes a new [MediaTypeReader] that matches a template against the media type.
    ///
    /// # Arguments
    ///
    /// * `extract` - the function that extracts the API version from a media type, which is typically generated by
    ///   [pattern!](crate::pattern)
    ///
    /// # Remarks
    ///
    /// Only the media type is matched against the template. Media type parameters, such as `charset` or `q`, are not.
    pub fn template(extract: fn(&str) -> Option<&str>) -> Self {
        Self(Matcher::Template(extract))
    }
}

/// Splits a media range into its media type and parameters.
fn split(media_range: &str) -> (&str, impl Iterator<Item = (&str, &str)>) {
    let mut parts = media_range.split(';');
    let media_type = parts.next().unwrap_or_default().trim();
    let params = parts.filter_map(|part| part.split_once('=').map(|(key, val)| (key.trim(), val.trim())));

    (media_type, params)
}

#[inline]
fn weight(quality: &str) -> f32 {
    quality.parse::<f32>().unwrap_or(0.0).clamp(0.0, DEFAULT_WEIGHT)
}

impl Matcher {
    /// Matches a single media range, returning the API version and its quality.
    fn matches<'a>(&self, media_range: &'a str) -> Option<(f32, &'a str)> {
        let (media_type, params) = split(media_range);
        let mut value = None;
        let mut quality = DEFAULT_WEIGHT;

        if let Matcher::Template(extract) = self {
            value = Some(extract(media_type)?);
        }

        for (key, val) in params {
            // media type parameter names are case-insensitive
            if key.eq_ignore_ascii_case("q") {
                quality = weight(val);
            } else if let Matcher::Parameters(names) = self
                && value.is_none()
                && names.iter().any(|name| key.eq_ignore_ascii_case(name))
            {
                value = Some(val);
            }
        }

        value.map(|v| (quality, v))
    }
}

#[inline]
fn acceptable(accept: &(f32, &str)) -> bool {
    const UNACCEPTABLE: f32 = 0.0;
    accept.0 > UNACCEPTABLE
}

impl Reader for MediaTypeReader {
    fn read<'a>(&self, request: &'a dyn RequestInfo) -> SmallVec<[&'a str; 1]> {
        let mut versions: SmallVec<[(f32, &'a str); 2]> = SmallVec::new();
        let mut max = 0.0;

        // content-type is always considered with a weight of 1.0
        if let Some(header) = request.headers().get(&CONTENT_TYPE)
            && let Ok(content_type) = header.to_str()
            && let Some((_, value)) = self.0.matches(content_type)
        {
            max = DEFAULT_WEIGHT;
            versions.push((DEFAULT_WEIGHT, value));
        }

        // consider all media ranges in all accept headers with a weight > 0.0
        for header in request.headers().get_all(&ACCEPT) {
            if let Ok(accept) = header.to_str() {
                for media_range in accept.split(',') {
                    if let Some(value) = self.0.matches(media_range)
                        && acceptable(&value)
                    {
                        max = max.max(value.0);
                        versions.push(value);
                    }
                }
            }
        }

        if versions.len() < 2 {
            versions.into_iter().map(|(_, v)| v).collect()
        } else {
            let mut ranked: SmallVec<[&'a str; 1]> = versions
                .into_iter()
                .filter_map(|(q, v)| if q == max { Some(v) } else { None })
                .collect();

            ranked.sort();
            ranked.dedup();
            ranked
        }
    }

    fn clone(&self) -> Box<dyn Reader> {
        Box::new(Clone::clone(self))
    }
}

impl Descriptor for MediaTypeReader {
    fn describe<'a>(&'a self, context: &mut dyn Context<'a>) {
        match &self.0 {
            Matcher::Parameters(names) => {
                for name in names {
                    context.register(name, MediaType);
                }
            }
            // a template has no parameter name
            Matcher::Template(_) => context.register("", MediaType),
        }
    }
}

/// Generates an API version extractor from a template.
///
/// The template is specified as a literal and must contain exactly one parameter, which is denoted by braces such as
/// `{v}`, `{ver}`, or `{version}`. The parameter name is user-defined, but must contain at least one visible character.
/// The template can be specified as unquoted tokens or as a string literal. A string literal should be used when the
/// template is not a valid sequence of Rust tokens.
///
/// The result is a `fn(&str) -> Option<&str>` that finds the first occurrence of the text before the parameter and
/// returns the one or more characters up to the next occurrence of the text after the parameter. When the parameter is
/// at the end of the template, the rest of the text is matched. A match does not have to include the entire text. The
/// text around the parameter is matched without regard to ASCII case because media types are case-insensitive; the
/// parameter value is returned as it appears in the text.
///
/// # Panics
///
/// Panics if the template is invalid. Since the template is validated in a constant expression, this causes a
/// compilation error.
///
/// # Examples
///
/// ```
/// use api_versioning::pattern;
///
/// let json = pattern!(application/vnd.{v}+json);
/// let xml = pattern!(application/vnd.v{ver}+xml);
/// let date = pattern!("application/vnd.{version}+json");
///
/// assert_eq!(json("application/vnd.1+json"), Some("1"));
/// assert_eq!(xml("application/vnd.v2.1+xml"), Some("2.1"));
/// assert_eq!(date("application/vnd.2026-10-25+json; charset=utf-8"), Some("2026-10-25"));
/// assert_eq!(json("application/json"), None);
/// ```
///
/// ```compile_fail
/// use api_versioning::pattern;
///
/// let extract = pattern!(application/vnd.{v}.{ver}+json);
/// ```
///
/// ```compile_fail
/// use api_versioning::pattern;
///
/// let extract = pattern!("application/vnd.{ }+json");
/// ```
#[macro_export]
macro_rules! pattern {
    ($template:literal) => {
        $crate::pattern!(@template concat!($template))
    };
    (@template $template:expr) => {{
        const PARTS: (&str, &str) = $crate::readers::__template::parse($template);

        fn extract(text: &str) -> ::core::option::Option<&str> {
            $crate::readers::__template::extract(text, PARTS.0, PARTS.1)
        }

        extract as fn(&str) -> ::core::option::Option<&str>
    }};
    ($($token:tt)+) => {
        $crate::pattern!(@template concat!($(stringify!($token)),+))
    };
}

#[doc(hidden)]
pub mod template {
    const fn text(bytes: &[u8]) -> &str {
        match str::from_utf8(bytes) {
            Ok(text) => text,
            Err(_) => panic!("the template is not valid UTF-8"),
        }
    }

    /// Parses the template into the text before and after its single parameter.
    pub const fn parse(template: &str) -> (&str, &str) {
        let bytes = template.as_bytes();
        let mut open = None;
        let mut close = None;
        let mut i = 0;

        while i < bytes.len() {
            match bytes[i] {
                b'{' if open.is_some() => panic!("the template must only contain a single parameter"),
                b'{' => open = Some(i),
                b'}' if open.is_none() || close.is_some() => panic!("the template contains an unexpected '}}'"),
                b'}' => close = Some(i),
                _ => {}
            }

            i += 1;
        }

        let (Some(open), Some(close)) = (open, close) else {
            panic!("the template must contain a parameter, such as {{v}}");
        };
        let mut visible = false;
        let mut i = open + 1;

        while i < close {
            visible |= !bytes[i].is_ascii_whitespace();
            i += 1;
        }

        if !visible {
            panic!("the template parameter name must contain at least one visible character");
        }

        let (prefix, _) = bytes.split_at(open);
        let (_, suffix) = bytes.split_at(close + 1);

        (text(prefix), text(suffix))
    }

    /// Finds the byte index of the first occurrence of the needle in the text, ignoring ASCII case.
    fn find(text: &str, needle: &str) -> Option<usize> {
        if needle.is_empty() {
            return Some(0);
        }

        // ASCII bytes only match ASCII bytes, so a match always starts and ends on a char boundary
        text.as_bytes()
            .windows(needle.len())
            .position(|window| window.eq_ignore_ascii_case(needle.as_bytes()))
    }

    /// Extracts the parameter value from the text using the parts of a parsed template.
    pub fn extract<'a>(text: &'a str, prefix: &str, suffix: &str) -> Option<&'a str> {
        // if the suffix doesn't follow the first prefix, it cannot follow a later one either
        let start = find(text, prefix)? + prefix.len();
        let rest = &text[start..];
        let first = rest.chars().next()?.len_utf8();

        if suffix.is_empty() {
            return Some(rest);
        }

        find(&rest[first..], suffix).map(|end| &rest[..first + end])
    }
}

