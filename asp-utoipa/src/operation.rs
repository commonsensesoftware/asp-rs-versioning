use api_versioning::{ApiVersion, visibility};
use utoipa::{
    __dev::{SchemaReferences, Tags},
    Path,
    openapi::{RefOr, Schema, path::HttpMethod},
};

/// Represents the named schemas referenced by an operation.
pub(crate) type Schemas = Vec<(String, RefOr<Schema>)>;

/// Represents the OpenAPI operation attached to a handler by [doc!](crate::doc).
#[derive(Clone)]
pub(crate) struct Operation {
    /// The HTTP methods the operation is declared for.
    pub methods: Vec<HttpMethod>,

    operation: fn() -> utoipa::openapi::path::Operation,
    schemas: fn(&mut Schemas),
    tags: Vec<String>,
}

impl Operation {
    /// Creates the operation generated by `#[utoipa::path]` for the specified type.
    pub fn of<P>() -> Self
    where
        P: Path + SchemaReferences + Tags<'static>,
    {
        Self {
            methods: P::methods(),
            operation: P::operation,
            schemas: P::schemas,
            tags: P::tags().into_iter().map(String::from).collect(),
        }
    }

    /// Describes the operation and the schemas it references in the specified API version.
    ///
    /// # Remarks
    ///
    /// The operation and schemas are created while the API version is [current](visibility::scope), so they only have
    /// the members that are visible in the API version.
    pub fn describe(&self, version: &ApiVersion<'static>) -> (utoipa::openapi::path::Operation, Schemas) {
        visibility::scope(Some(version.clone()), || {
            let mut operation = (self.operation)();
            let mut schemas = Vec::new();

            if !self.tags.is_empty() {
                operation
                    .tags
                    .get_or_insert_with(Vec::new)
                    .extend(self.tags.iter().cloned());
            }

            (self.schemas)(&mut schemas);
            (operation, schemas)
        })
    }
}
