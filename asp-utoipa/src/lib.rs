/// Describes a handler with the OpenAPI operation generated by `#[utoipa::path]`.
///
/// # Arguments
///
/// * `handler` - the path to a handler function annotated with `#[utoipa::path]`, such as `get_orders` or
///   `v1::orders::get`
///
/// # Remarks
///
/// The result is a [Described](api_versioning_axum::Described) handler that is added to an API in place of the handler.
/// The handler is unchanged; only its OpenAPI operation, HTTP methods, and the schemas it references are attached.
///
/// # Examples
///
/// ```
/// use api_versioning::{Options, api_version};
/// use api_versioning_axum::Router;
/// use api_versioning_utoipa::doc;
///
/// #[utoipa::path(get, path = "", responses((status = 200, body = String)))]
/// async fn get_orders() -> &'static str {
///     "orders"
/// }
///
/// let app: axum::Router = Router::new(Options::default())
///     .api("/orders", |api| api.has(api_version!(1.0)).route("/", |e| e.get(doc!(get_orders))))
///     .into();
/// ```
#[macro_export]
macro_rules! doc {
    ($($handler:tt)+) => {
        $crate::__private::describe_operation!($crate; $($handler)+)
    };
}

#[doc(hidden)]
pub mod __private {
    use crate::operation::Operation;
    use api_versioning_axum::Described;
    use utoipa::{
        __dev::{SchemaReferences, Tags},
        Path,
    };

    pub use api_versioning_macros::__describe_operation as describe_operation;

    /// Describes the specified handler with the OpenAPI operation generated for it by `#[utoipa::path]`.
    pub fn describe<P, H>(handler: H) -> Described<H>
    where
        P: Path + SchemaReferences + Tags<'static>,
    {
        Described::new(handler).with(Operation::of::<P>())
    }
}
