//! Provides the procedural macros for API versioning.
//!
//! The macros are intended to be used through the `api-versioning` crate with the `macros` feature.

mod openapi;
mod visibility;

use proc_macro::TokenStream;

/// Makes the members of a struct visible only in specific API versions when they are serialized and deserialized.
///
/// # Remarks
///
/// Each member with a `#[range(..)]` attribute is visible only in the API versions within at least one of its ranges.
/// Each range is a Rust range of API versions, such as `2.0..`, `..3.0`, `2.0..3.0`, or `2.0..=3.0`, using the same
/// syntax as [api_version!](https://docs.rs/api-versioning/latest/api_versioning/macro.api_version.html). A single API
/// version is not a range; `2.0..=2.0` matches exactly one API version.
///
/// * A hidden member is not serialized
/// * A hidden member that is deserialized is rejected because it is not part of the API version; accepting it would
///   allow over-posting
/// * A hidden member that is absent uses its default value, so its type must implement [Default]
/// * Every member is visible when there is no current API version, such as outside of a request
///
/// API versions with different formats are not comparable, so they are never in the same range. The current API
/// version is provided by the HTTP integration or by `api_versioning::visibility::scope`.
///
/// The attribute must be placed before `#[derive(Serialize, Deserialize)]` so that the derive sees the serde attributes
/// it adds. It cannot be combined with the serde `with`, `deserialize_with`, `skip_serializing_if`, or `skip*`
/// attributes on the same member.
///
/// # OpenAPI
///
/// When the struct also derives utoipa's `ToSchema`, its schema only has the members visible in the current API version.
/// Every member is in the schema when there is no current API version. `api-versioning-utoipa` creates the schemas of
/// each OpenAPI document in its API version. `ToSchema` must be derived by a `#[derive(..)]` after
/// `#[visible_in_version]` rather than through `cfg_attr`.
///
/// The schema is derived for hidden copies of the struct, so `ToSchema` is implemented by the macro and the
/// `#[schema(..)]` attributes apply to the copies. The generated code refers to the `utoipa` crate, just as the code
/// generated by `ToSchema` does.
///
/// # Arguments
///
/// * `crate = "path"` - the path to the `api-versioning` crate, which defaults to `::api_versioning`
///
/// # Examples
///
/// ```
/// use api_versioning::{api_version, visibility, visible_in_version};
/// use serde::{Deserialize, Serialize};
///
/// #[visible_in_version]
/// #[derive(Deserialize, Serialize)]
/// struct Order {
///     id: u32,
///     #[range(2.0..=3.0, 4.0..)]
///     customer: Option<String>,
/// }
///
/// let order = Order { id: 1, customer: Some("Bill".into()) };
/// let write = |version| visibility::scope(Some(version), || serde_json::to_string(&order).unwrap());
///
/// assert_eq!(write(api_version!(1.0)), r#"{"id":1}"#);
/// assert_eq!(write(api_version!(2.0)), r#"{"id":1,"customer":"Bill"}"#);
/// assert_eq!(write(api_version!(3.1)), r#"{"id":1}"#);
/// assert_eq!(write(api_version!(4.0)), r#"{"id":1,"customer":"Bill"}"#);
///
/// let read = |version| visibility::scope(Some(version), || serde_json::from_str::<Order>(r#"{"id":1,"customer":"Bill"}"#));
///
/// assert!(read(api_version!(2.0)).is_ok());
/// assert!(read(api_version!(1.0)).is_err());
/// ```
///
/// A single API version is not a range.
///
/// ```compile_fail
/// # use api_versioning::visible_in_version;
/// # use serde::Serialize;
/// #[visible_in_version]
/// #[derive(Serialize)]
/// struct Order {
///     #[range(2.0)]
///     customer: Option<String>,
/// }
/// ```
///
/// An invalid API version is a compile-time error.
///
/// ```compile_fail
/// # use api_versioning::visible_in_version;
/// # use serde::Serialize;
/// #[visible_in_version]
/// #[derive(Serialize)]
/// struct Order {
///     #[range(2.x..)]
///     customer: Option<String>,
/// }
/// ```
///
/// The attribute must be placed before the derive.
///
/// ```compile_fail
/// # use api_versioning::visible_in_version;
/// # use serde::Serialize;
/// #[derive(Serialize)]
/// #[visible_in_version]
/// struct Order {
///     #[range(2.0..)]
///     customer: Option<String>,
/// }
/// ```
#[proc_macro_attribute]
pub fn visible_in_version(args: TokenStream, item: TokenStream) -> TokenStream {
    visibility::expand(args.into(), item.into())
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

/// Describes a handler with the OpenAPI operation generated by `#[utoipa::path]`.
///
/// # Remarks
///
/// This macro is an implementation detail of `api_versioning_utoipa::doc!`. The input is the path to the crate that
/// defines `__private::describe`, a semicolon, and the path to the handler.
#[doc(hidden)]
#[proc_macro]
pub fn __describe_operation(input: TokenStream) -> TokenStream {
    openapi::expand(input.into())
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}
